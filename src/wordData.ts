export const wordItems: WordItem[] = wordSourceText
  .split("\n")
  .map((line) => line.trim())
  .filter(Boolean)
  .map((line) => {
    const match = line.match(/^(.+?)(?:\s*:\s*|\s*=\s*)(.+)$/);
    if (!match) {
      return null;
    }

    return {
      term: match[1].trim(),
      meaning: match[2].trim()
    };
  })
  .filter((item): item is WordItem => Boolean(item?.term && item.meaning));
